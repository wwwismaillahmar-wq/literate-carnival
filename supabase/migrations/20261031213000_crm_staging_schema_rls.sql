-- Staging-only migration. DO NOT apply to a database shared with production.
-- The CRM API uses crm_lead_activities, not leads_activity.
begin;
alter table public.leads
  add column if not exists assigned_to uuid references auth.users(id) on delete set null,
  add column if not exists updated_at timestamptz not null default now();
alter table public.leads enable row level security;
drop policy if exists leads_crm_select on public.leads;
drop policy if exists leads_crm_update on public.leads;
create policy leads_crm_select on public.leads for select to authenticated
 using (public.check_permission(auth.uid(),'crm.manage'));
create policy leads_crm_update on public.leads for update to authenticated
 using (public.check_permission(auth.uid(),'crm.manage'))
 with check (public.check_permission(auth.uid(),'crm.manage'));
-- Retain the public INSERT policy for incoming requests; no public SELECT.
create table if not exists public.crm_lead_activities (
 id bigint generated by default as identity primary key,
 lead_id bigint not null references public.leads(id) on delete cascade,
 activity_type text not null check (activity_type in ('note','call','email','whatsapp','meeting','follow_up','status_change')),
 body text not null check (char_length(body) between 1 and 4000),
 follow_up_at timestamptz,
 created_by uuid not null references auth.users(id),
 created_at timestamptz not null default now()
);
create index if not exists crm_lead_activities_lead_created_idx
 on public.crm_lead_activities(lead_id,created_at desc);
alter table public.crm_lead_activities enable row level security;
revoke all on public.crm_lead_activities from anon;
grant select,insert on public.crm_lead_activities to authenticated;
drop policy if exists crm_activities_select on public.crm_lead_activities;
drop policy if exists crm_activities_insert on public.crm_lead_activities;
create policy crm_activities_select on public.crm_lead_activities for select to authenticated
 using (public.check_permission(auth.uid(),'crm.manage'));
create policy crm_activities_insert on public.crm_lead_activities for insert to authenticated
 with check (created_by=auth.uid() and public.check_permission(auth.uid(),'crm.manage'));
-- All changes of lead status or assignee go through an authenticated, audited RPC.
create or replace function public.admin_update_crm_lead(p_lead_id bigint,p_status text,p_assigned_to uuid)
returns setof public.leads language plpgsql security invoker set search_path=''
as $$
declare v_lead public.leads;
begin
 if auth.uid() is null or not public.check_permission(auth.uid(),'crm.manage') then
   raise exception 'CRM_FORBIDDEN';
 end if;
 if p_status not in ('new','in_progress','completed') then
   raise exception 'INVALID_CRM_STATUS';
 end if;
 if p_assigned_to is not null and not exists(select 1 from auth.users where id=p_assigned_to) then
   raise exception 'LEAD_ASSIGNEE_NOT_FOUND';
 end if;
 update public.leads set status=p_status,assigned_to=p_assigned_to,updated_at=now()
 where id=p_lead_id returning * into v_lead;
 if not found then raise exception 'LEAD_NOT_FOUND'; end if;
 insert into public.crm_lead_activities(lead_id,activity_type,body,created_by)
 values(p_lead_id,'status_change','Updated status to '||p_status,auth.uid());
 return next v_lead;
end;
$$;
revoke all on function public.admin_update_crm_lead(bigint,text,uuid) from public,anon;
grant execute on function public.admin_update_crm_lead(bigint,text,uuid) to authenticated;
commit;